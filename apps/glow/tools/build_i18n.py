"""Build the Glow UI translation files from the phrase lists in tools/i18n/*.txt.

Each line: English || Bahasa Indonesia || 简体中文
Lines starting with "re:" are regular expressions ($1, $2 … keep the captured text).
Traditional Chinese (繁體中文, Taiwan usage) is generated from the Simplified text with OpenCC
(s2twp) plus a few fixes, so only two languages need to be written by hand.

Output: web/shared/i18n/ui.<lang>.js (one per language, loaded only when that language is chosen).
Run:  python apps/glow/tools/build_i18n.py      (needs: pip install opencc-python-reimplemented)
"""
import json
import re
import sys
from pathlib import Path

from opencc import OpenCC

APP = Path(__file__).resolve().parent.parent
SOURCES = sorted((APP / "tools" / "i18n").glob("*.txt"))
OUT = APP / "web" / "shared" / "i18n"

# OpenCC s2twp gets most Taiwan wording right; these are the remaining differences.
TW_FIXES = {
    "賬": "帳",
    "二維碼": "QR Code",
    "質量": "品質",
    "人設": "角色設定",
    "劇本": "腳本",
}


def to_taiwan(text, converter):
    converted = converter.convert(text)
    for wrong, right in TW_FIXES.items():
        converted = converted.replace(wrong, right)
    return converted


def main():
    converter = OpenCC("s2twp")
    phrases = {}
    patterns = []
    problems = []
    for source in SOURCES:
        for number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = [part.strip() for part in line.split("||")]
            if len(parts) != 3 or not all(parts):
                problems.append(f"{source.name}:{number}: needs 'English || Indonesian || Chinese'")
                continue
            english, indonesian, chinese = parts
            row = {"id": indonesian, "zh-CN": chinese, "zh-TW": to_taiwan(chinese, converter)}
            if english.startswith("re:"):
                expression = english[3:]
                try:
                    re.compile(expression)
                except re.error as error:
                    problems.append(f"{source.name}:{number}: bad pattern ({error})")
                    continue
                patterns.append((expression, row))
            else:
                if english in phrases and phrases[english]["zh-CN"] != chinese:
                    problems.append(f"{source.name}:{number}: '{english}' translated twice differently")
                phrases[english] = row
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    OUT.mkdir(parents=True, exist_ok=True)
    for lang in ("id", "zh-CN", "zh-TW"):
        payload = {
            "lang": lang,
            "phrases": {english: row[lang] for english, row in phrases.items()},
            "patterns": [[expression, row[lang]] for expression, row in patterns],
        }
        body = json.dumps(payload, ensure_ascii=False, indent=0, sort_keys=True)
        text = (
            "// Generated by apps/glow/tools/build_i18n.py from tools/i18n/*.txt. Do not edit by hand.\n"
            f"window.GlowLocale && window.GlowLocale.registerStrings({body});\n"
        )
        (OUT / f"ui.{lang}.js").write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(phrases)} phrases, {len(patterns)} patterns -> {OUT}")


if __name__ == "__main__":
    main()
