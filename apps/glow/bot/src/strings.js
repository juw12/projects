const STRINGS = { en, id, "zh-Hans": zhHans, "zh-Hant": zhHant };

export const STRING_KEYS = Object.keys(en);

export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function lookup(lang, key) {
  const table = STRINGS[lang] || en;
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  if (Object.prototype.hasOwnProperty.call(en, key)) return en[key];
  return null;
}

function fill(template, vars, escape) {
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z]+)\}/g, (whole, name) => {
    if (!Object.prototype.hasOwnProperty.call(vars, name)) return whole;
    const value = String(vars[name] ?? "");
    return escape ? escapeHtml(value) : value;
  });
}

// Telegram HTML. Every value dropped into the text is escaped here, so callers pass raw text.
export function t(lang, key, vars) {
  const template = lookup(lang, key);
  if (template === null) return escapeHtml(key);
  return fill(template, vars, true);
}

// Plain text, for the places Telegram shows without markup (toasts, command menu, bot profile).
export function tPlain(lang, key, vars) {
  const template = lookup(lang, key);
  if (template === null) return key;
  return fill(template, vars, false);
}

export const COMMANDS = [
  "lead", "room", "chat", "agent", "ask", "agents", "news", "spark", "apps", "status", "stop", "lang", "daily", "every",
  "missions", "help",
];

export function commandList(lang) {
  return COMMANDS.map((command) => ({ command, description: tPlain(lang, `cmd.${command}`) }));
}

export function stringsFor(lang) {
  return STRINGS[lang] || en;
}
