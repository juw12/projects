export const LANGS = ["en", "id", "zh-Hans", "zh-Hant"];

export const LANG_NAMES = {
  en: "English",
  id: "Bahasa Indonesia",
  "zh-Hans": "简体中文",
  "zh-Hant": "繁體中文",
};

// Telegram sends IETF tags such as "en", "id", "zh-hans", "zh-hant" (older apps: "zh-CN", "zh-TW").
export function pickLang(code) {
  const value = String(code || "").trim().toLowerCase().replace(/_/g, "-");
  if (!value) return "en";
  if (value === "id" || value.startsWith("id-") || value === "in" || value === "ms" || value.startsWith("ms-")) return "id";
  if (value.startsWith("zh")) {
    if (/hant|-tw|-hk|-mo/.test(value)) return "zh-Hant";
    return "zh-Hans";
  }
  return "en";
}

export function isLang(code) {
  return LANGS.includes(code);
}

