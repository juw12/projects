"""Builds the bot's copies of logic that lives in the Glow web apps.

The bot has to search and parse exactly like the web apps do, so those pieces are sliced out of
the web sources by name instead of being typed a second time. Run this after changing a source:

    python apps/glow/bot/tools/make_ports.py          # rewrite the ports
    python apps/glow/bot/tools/make_ports.py --check  # exit 1 when a port is out of date
"""
import sys
from pathlib import Path

BOT = Path(__file__).resolve().parents[1]
WEB = BOT.parent / "web"
INDENT = "  "  # the web sources wrap everything in one function, so its members sit two spaces in


def find_block(lines, kind, name):
    """Return one member of the source's wrapping function, with the comment lines right above it."""
    opening = f"{INDENT}{kind} {name}" + ("(" if kind == "function" else " =")
    starts = [index for index, line in enumerate(lines) if line.startswith(opening)]
    if len(starts) != 1:
        raise SystemExit(f"expected exactly one '{opening.strip()}' but found {len(starts)}")
    start = starts[0]
    end = start
    if kind == "function":
        while lines[end] != INDENT + "}":
            end += 1
    elif not lines[start].rstrip().endswith(";"):
        end += 1
        while not (lines[end].startswith(INDENT) and lines[end][len(INDENT)] in "]})" and lines[end].rstrip().endswith(";")):
            end += 1
    first = start
    while first > 0 and lines[first - 1].startswith(INDENT + "//") and not lines[first - 1].startswith(INDENT + "// ==="):
        first -= 1
    return [line[len(INDENT):] if line.startswith(INDENT) else line for line in lines[first:end + 1]]


def build_port(source, members, note):
    lines = source.read_text(encoding="utf-8").splitlines()
    relative = source.relative_to(BOT.parent.parent.parent).as_posix()
    out = [
        f"// GENERATED by tools/make_ports.py from {relative}.",
        "// Do not edit by hand: change the source, then run the script again.",
        f"// {note}",
        "",
    ]
    for kind, name in members:
        out.extend(find_block(lines, kind, name))
        out.append("")
    names = ", ".join(name for _, name in members)
    out.append(f"export {{ {names} }};")
    return "\n".join(out) + "\n"


PORTS = [
    (
        BOT / "src" / "crew-port.js",
        WEB / "room" / "crew-engine.js",
        [
            ("function", "truncate"),
            ("function", "decodeResultUrl"),
            ("const", "SEARCH_ENGINE_HOSTS"),
            ("function", "parseSearchMarkdown"),
            ("const", "SEARCH_ENGINES"),
            ("const", "STOP_WORDS"),
            ("function", "relevantExcerpt"),
            ("function", "looksLikeLeakedReasoning"),
        ],
        "GlowRoom's search-result parser and page-excerpt picker, so Scout reads the web the same way in Telegram.",
    ),
]


def main():
    check_only = "--check" in sys.argv[1:]
    stale = []
    for target, source, members, note in PORTS:
        wanted = build_port(source, members, note)
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else None
        if current == wanted:
            print(f"up to date: {target.name}")
            continue
        if check_only:
            stale.append(target.name)
            print(f"OUT OF DATE: {target.name}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(wanted, encoding="utf-8", newline="\n")
        print(f"wrote {target.name}")
    if stale:
        print("Run: python apps/glow/bot/tools/make_ports.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
