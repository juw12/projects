"""Build web/i18n-strings.js from the translation sources in this folder.

    python apps/airiz-motor/i18n/build_i18n.py

zh-TW.json is the hand-written source (Traditional Chinese, Taiwan wording).
zh-CN is generated from it with OpenCC (tw2sp: Taiwan phrases -> Simplified Chinese, mainland
phrases), then zh-CN-overrides.json fixes individual entries if needed.
Requires: pip install opencc-python-reimplemented
"""
import json
import re
from pathlib import Path

import opencc

HERE = Path(__file__).resolve().parent
WEB = HERE.parent / "web"
OUTPUT = WEB / "i18n-strings.js"
# Mainland wording that OpenCC leaves in Taiwan style (applied after conversion, in order).
MAINLAND_PHRASES = [
    ("安装档", "安装包"),
    ("存成", "保存为"),
    (" 档", " 文件"),
    ("档，", "文件，"),
    ("鲍率", "波特率"),
    ("工作阶段", "会话"),
    ("重设", "重置"),
    ("影像", "图像"),
    ("拷贝", "复制"),
    ("回应", "响应"),
]


def load(name):
    path = HERE / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def convert_entry(converter, value):
    # Keep HTML tags, ${placeholders} and $1 groups untouched; convert only the text between them.
    parts = re.split(r"(<[^>]+>|\$\d)", value)
    return "".join(part if part.startswith("<") or re.fullmatch(r"\$\d", part or "x") else mainland(converter.convert(part))
                   for part in parts)


def mainland(text):
    for old, new in MAINLAND_PHRASES:
        text = text.replace(old, new)
    return text


def simplified(source, overrides):
    converter = opencc.OpenCC("tw2sp")
    result = {
        "text": {key: convert_entry(converter, value) for key, value in source["text"].items()},
        "html": {key: convert_entry(converter, value) for key, value in source["html"].items()},
        "patterns": [[pattern, convert_entry(converter, target)] for pattern, target in source["patterns"]],
    }
    result["text"].update(overrides.get("text", {}))
    result["html"].update(overrides.get("html", {}))
    return result


def check(name, table):
    for pattern, _ in table["patterns"]:
        re.compile(pattern)
    for key in table["text"]:
        if key != re.sub(r"\s+", " ", key).strip():
            raise SystemExit(f"{name}: key is not whitespace-normalised: {key!r}")


def main():
    traditional = load("zh-TW.json")
    traditional = {key: traditional[key] for key in ("text", "html", "patterns")}
    simplified_table = simplified(traditional, load("zh-CN-overrides.json"))
    for name, table in (("zh-TW", traditional), ("zh-CN", simplified_table)):
        check(name, table)
    bundle = {"zh-TW": traditional, "zh-CN": simplified_table}
    OUTPUT.write_text(
        "/* Generated by apps/airiz-motor/i18n/build_i18n.py from i18n/zh-TW.json. Do not edit by hand. */\n"
        "window.AIRIZ_I18N_STRINGS = " + json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"{OUTPUT}: {len(traditional['text'])} strings, {len(traditional['html'])} paragraphs, "
          f"{len(traditional['patterns'])} patterns per language")


if __name__ == "__main__":
    main()
