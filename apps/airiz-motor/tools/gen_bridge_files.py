"""Embed the Bluetooth bridge files into the web console (web/data/bridge-files.js).

The console's "Phone remote" button uploads these to /data/airiz on the device over
the USB serial console. Run after editing anything in bluetooth-bridge/.
"""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = ["bridge.sh", "start.sh", "stop.sh", "bus.conf"]


def build():
    entries = []
    for name in FILES:
        data = (ROOT / "bluetooth-bridge" / name).read_bytes().replace(b"\r\n", b"\n")
        entries.append({
            "name": name,
            "md5": hashlib.md5(data).hexdigest(),
            "base64": base64.b64encode(data).decode(),
        })
    body = json.dumps(entries, indent=2)
    return ("/* Generated by tools/gen_bridge_files.py from bluetooth-bridge/. Do not edit. */\n"
            "window.AIRIZ_BRIDGE_FILES = Object.freeze(" + body + ");\n")


if __name__ == "__main__":
    target = ROOT / "web" / "data" / "bridge-files.js"
    target.write_text(build(), encoding="utf-8", newline="\n")
    print("Wrote", target)
